import {test,expect} from '@playwright/test';
import {promises as fs} from 'node:fs';
import {createHash} from 'node:crypto';
test('native desktop invitation transfers the actual synthetic source',async({page})=>{
  test.setTimeout(120000);
  const codePath=process.env.NINGMAO_NATIVE_CODE_FILE!,source=process.env.NINGMAO_NATIVE_SOURCE!;
  let code='';
  await expect.poll(async()=>{try{code=(await fs.readFile(codePath,'utf8')).trim();return code.length;}catch{return 0;}},{timeout:90000}).toBe(36);
  await page.goto('http://127.0.0.1:53323');
  await page.getByRole('button',{name:'Receive files',exact:true}).click();
  const panel=page.locator('.receive-panel');
  await panel.getByLabel('Croc code or stored link').fill(code);
  await panel.getByLabel('Croc code or stored link').press('Enter');
  await expect(panel.getByRole('button',{name:'Download files',exact:true})).toBeVisible();
  await page.evaluate(()=>Object.defineProperty(window,'showDirectoryPicker',{configurable:true,value:undefined}));
  const downloading=page.waitForEvent('download');
  await panel.getByRole('button',{name:'Download files',exact:true}).click();
  const download=await downloading;
  const bytes=await fs.readFile((await download.path())!);
  const expected=await fs.readFile(source);
  expect(createHash('sha256').update(bytes).digest('hex')).toBe(createHash('sha256').update(expected).digest('hex'));
  expect(bytes.toString()).toBe('Ningmao native browser share synthetic payload');
});
