import {expect,test} from '@playwright/test';

test('内置规则可停用并保留成果，撤销仅移除本次新加标签',async({page})=>{
  await page.addInitScript(()=>{if(!localStorage.getItem('test-state'))localStorage.setItem('test-state',JSON.stringify({shelves:[{id:1,name:'规则验收',kind:'persistent',root:null,available:true}],items:[{id:1,shelf_id:1,name:'已有分类.png',path:'SYNTHETIC/已有分类.png',kind:'png',bytes:8,modified:1,status:'normal',tags:['图片']},{id:2,shelf_id:1,name:'新素材.png',path:'SYNTHETIC/新素材.png',kind:'png',bytes:8,modified:1,status:'normal',tags:[]}],jobs:[]}));});
  await page.goto('/tests/harness.html?manager');
  await page.getByRole('button',{name:'素材',exact:true}).click();
  await page.getByRole('checkbox',{name:'选择本页文件',exact:true}).check();
  await page.getByRole('button',{name:'生成本地规则建议',exact:true}).click();
  const rules=page.getByRole('region',{name:'本地规则建议',exact:true});
  await expect(rules.getByRole('button',{name:'停用本地规则',exact:true})).toBeVisible();
  await rules.getByRole('button',{name:'添加标签 图片',exact:true}).click();
  const tags=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('test-state')!).items.map((i:{tags:string[]})=>i.tags));
  expect(await tags()).toEqual([['图片'],['图片']]);
  await rules.getByRole('button',{name:'撤销本次规则添加',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('已撤销');
  expect(await tags()).toEqual([['图片'],[]]);
  await rules.getByRole('button',{name:'添加标签 图片',exact:true}).click();
  await rules.getByRole('button',{name:'停用本地规则',exact:true}).click();
  await expect(rules).toContainText('本地规则已停用');
  expect(await tags()).toEqual([['图片'],['图片']]);
  await page.reload();
  await page.getByRole('button',{name:'素材',exact:true}).click();
  await page.getByRole('checkbox',{name:'选择本页文件',exact:true}).check();
  await page.getByRole('button',{name:'生成本地规则建议',exact:true}).click();
  await expect(rules).toContainText('本地规则已停用');
  await expect(rules.getByRole('button',{name:/^添加标签 /})).toHaveCount(0);
  expect(await tags()).toEqual([['图片'],['图片']]);
  await rules.getByRole('button',{name:'启用本地规则',exact:true}).click();
  await expect(rules).toContainText('暂无新的规则建议');
});
