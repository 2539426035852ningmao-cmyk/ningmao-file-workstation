import { test,expect } from "@playwright/test";
import path from "node:path";
const screenshots=process.env.M105_SCREENSHOTS;
async function settle(page:import("@playwright/test").Page) {
  await page.evaluate(async()=>{await new Promise<void>(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve())));await Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{})));});
}
test("引用、标签、失效状态、预览与移除语义",async({page})=>{
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/tests/harness.html");
  await expect(page.getByRole("button",{name:"选择 Alpha.txt",exact:true})).toBeVisible();
  await page.getByLabel("搜索文件").fill("中文");
  await expect(page.locator("[data-item-id]")).toHaveCount(1);
  await page.getByLabel("搜索文件").fill("");
  await page.getByRole("button",{name:"选择 Alpha.txt",exact:true}).click({button:"right"});
  await page.getByRole("menuitem",{name:"标记精选",exact:true}).click();
  await page.getByRole("button",{name:"选择 Alpha.txt",exact:true}).click();
  await page.keyboard.press("Space");await expect(page.getByRole("dialog")).toBeVisible();
  await expect(page.getByRole("dialog")).toContainText("精选");
  await page.keyboard.press("Escape");await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.evaluate(()=>window.testHarness.missing(1));await page.getByLabel("刷新文件状态").click();
  await expect(page.locator('[data-item-id="1"]')).toContainText("引用失效");
  await page.getByRole("button",{name:"选择 Alpha.txt",exact:true}).click();
  await expect(page.getByRole("button",{name:"拖出复制",exact:true})).toBeDisabled();
  await page.keyboard.press("Delete");await expect(page.locator('[data-item-id="1"]')).toHaveCount(0);
  expect(await page.evaluate(()=>window.testHarness.calls())).toContain("remove:1");
  await page.reload();await expect(page.locator("[data-item-id]")).toHaveCount(2);
  expect(errors).toEqual([]);
});
test("拖入路由、绑定目录、复制进度、取消与失败反馈",async({page})=>{
  await page.goto("/tests/harness.html");
  await page.evaluate(()=>window.testHarness.drop(["SYNTHETIC/drop.txt"]));
  await expect(page.getByRole("button",{name:"选择 drop.txt",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"选择 drop.txt",exact:true}).click();
  await page.getByRole("button",{name:"绑定文件夹",exact:true}).click();
  await expect(page.getByRole("heading",{name:"测试绑定目录",exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"拖出复制",exact:true})).toHaveCount(0);
  await page.getByRole("button",{name:"添加并复制",exact:true}).click();
  await expect(page.getByRole("progressbar",{name:"当前文件复制进度"})).toBeVisible();
  await page.getByRole("button",{name:"取消复制",exact:true}).click();
  await expect(page.getByText("已取消",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"添加并复制",exact:true}).click();
  await page.evaluate(()=>window.testHarness.complete());
  await expect(page.getByRole("button",{name:"选择 新增文件 (1).txt",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"选择 新增文件 (1).txt",exact:true}).click({button:"right"});
  await expect(page.getByRole("menuitem",{name:"仅移除引用（保留原文件）"})).toHaveAttribute("data-disabled","");
  await page.keyboard.press("Escape");
  await page.evaluate(()=>window.testHarness.fail("模拟权限不足：未修改原文件"));
  await page.getByRole("button",{name:"添加并复制",exact:true}).click();
  await expect(page.getByRole("alert")).toContainText("模拟权限不足");
});
test("手动排序中途反馈、持久顺序、深浅主题与窄窗详情",async({page})=>{
  await page.goto("/tests/harness.html");
  const source=page.locator('[data-item-id="1"]'),target=page.locator('[data-item-id="3"]');
  await source.hover();
  const handle=await source.getByRole("button",{name:"调整 Alpha.txt 顺序"}).boundingBox();
  const to=await target.boundingBox();if(!handle||!to)throw Error("missing boxes");
  await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await page.mouse.down();
  await page.mouse.move(to.x+to.width/2,to.y+to.height/2,{steps:18});
  await expect(page.getByTestId("drag-preview")).toBeVisible();
  await page.mouse.up();
  await expect.poll(()=>page.locator("[data-item-id]").evaluateAll(nodes=>nodes.map(n=>n.getAttribute("data-item-id")))).toEqual(["2","3","1"]);
  await page.reload();
  await expect(page.locator("[data-item-id]").first()).toHaveAttribute("data-item-id","2");
  await settle(page);
  const name=page.locator(".asset-name").first();
  expect(await name.evaluate(n=>n.clientHeight>=parseFloat(getComputedStyle(n).lineHeight))).toBe(true);
  if(screenshots)await page.screenshot({path:path.join(screenshots,"desktop-dark.png")});
  await page.getByRole("button",{name:"切换浅色主题"}).click();
  await settle(page);
  if(screenshots)await page.screenshot({path:path.join(screenshots,"desktop-light.png")});
  await page.setViewportSize({width:640,height:720});
  await page.getByRole("button",{name:"选择 Alpha.txt",exact:true}).dblclick();
  await expect(page.getByRole("dialog")).toBeVisible();
  await expect(page.getByRole("dialog")).toContainText("SYNTHETIC/Alpha.txt");
  await settle(page);
  if(screenshots)await page.screenshot({path:path.join(screenshots,"desktop-narrow.png")});
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).not.toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
