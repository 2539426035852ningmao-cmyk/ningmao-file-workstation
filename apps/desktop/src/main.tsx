import React from "react";
import ReactDOM from "react-dom/client";
import { isTauri } from "@tauri-apps/api/core";
import App from "./App";
import DesktopEntry from "./DesktopEntry";
import Manager from "./Manager";
import {getCurrentWebviewWindow} from "@tauri-apps/api/webviewWindow";
import { detachedShelfFromLabel,nativeBackend } from "./backend";
import "./style.css";
const entry=isTauri() && getCurrentWebviewWindow().label==="desktop-entry";
const manager=isTauri() && getCurrentWebviewWindow().label==="manager";
const ownShelf=isTauri()?detachedShelfFromLabel(getCurrentWebviewWindow().label):undefined;
ReactDOM.createRoot(document.getElementById("root")!).render(<React.StrictMode>{entry?<DesktopEntry backend={nativeBackend}/>:manager?<Manager backend={nativeBackend}/>:<App backend={nativeBackend} native={isTauri()} detachedShelfId={ownShelf}/>}</React.StrictMode>);
